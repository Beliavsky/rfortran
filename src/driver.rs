//! Shared native build driver; source inputs are compiled together in caller order.
use crate::{cli::Cli, compile_to_object, linker, utils};
use anyhow::{bail, Context, Result};
use std::{
    fs,
    path::{Path, PathBuf},
};

const MARKER: &str = "! Generated by rfort; do not edit.";
const LEGACY_MARKER: &str = "! Generated by f90c.bat; do not edit.";

fn identity(path: &Path) -> Result<PathBuf> {
    if path.exists() {
        return Ok(path.canonicalize()?);
    }
    let parent = path
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    Ok(parent
        .canonicalize()?
        .join(path.file_name().context("output has no filename")?))
}

fn protect_output(output: &Path, inputs: &[PathBuf]) -> Result<()> {
    let output = identity(output)?;
    for input in inputs {
        let input = input.canonicalize()?;
        if input == output
            || (cfg!(windows)
                && input
                    .to_string_lossy()
                    .eq_ignore_ascii_case(&output.to_string_lossy()))
        {
            bail!("Output would overwrite input: {}", input.display());
        }
    }
    Ok(())
}

fn combine(sources: &[PathBuf], output: &Path, inputs: &[PathBuf]) -> Result<Vec<crate::source_diagnostics::SourceOrigin>> {
    protect_output(output, inputs)?;
    if output.exists() {
        let old = utils::read_file_to_string(output)?;
        if !matches!(old.lines().next(), Some(MARKER | LEGACY_MARKER)) {
            bail!(
                "Refusing to overwrite a file not generated by rfort: {}",
                output.display()
            );
        }
    }
    let mut text = format!("{MARKER}\n");
    let mut origins=vec![];
    for source in sources {
        let source = source.canonicalize()?;
        text.push_str(&format!("! Source: {}\n", source.display()));
        let start=text.len();
        text.push_str(&utils::read_file_to_string(&source)?);
        origins.push(crate::source_diagnostics::SourceOrigin{name:source.display().to_string(),range:start..text.len()});
        text.push('\n');
    }
    fs::write(output, text).with_context(|| format!("writing {}", output.display()))?;
    Ok(origins)
}

pub fn build(
    inputs: &[PathBuf],
    out: Option<PathBuf>,
    run: bool,
    force_link: bool,
    cli: &Cli,
) -> Result<()> {
    if inputs.is_empty() {
        bail!("No input files supplied");
    }
    if run && cli.compile_only {
        bail!("--run cannot be combined with --compile-only");
    }
    let mut sources = Vec::new();
    let mut objects = Vec::new();
    for input in inputs {
        if !input.is_file() {
            bail!("Source file not found: {}", input.display());
        }
        match input
            .extension()
            .and_then(|e| e.to_str())
            .unwrap_or("")
            .to_ascii_lowercase()
            .as_str()
        {
            "f90" | "f95" | "f03" | "f08" => sources.push(input.clone()),
            "obj" | "o" => objects.push(input.clone()),
            _ => bail!(
                "Unsupported input type: {} (expected free-form Fortran or an object)",
                input.display()
            ),
        }
    }
    if cli.compile_only && !objects.is_empty() {
        bail!("--compile-only requires Fortran sources, not object inputs");
    }
    let base = sources.last().or_else(|| objects.first()).unwrap();
    let exe = out
        .clone()
        .unwrap_or_else(|| utils::default_exe_output_path(base));
    let object = if cli.compile_only {
        out.unwrap_or_else(|| utils::default_object_output_path(base))
    } else {
        utils::default_object_output_path(base)
    };
    if !cli.compile_only {
        protect_output(&exe, inputs)?;
    }
    if !sources.is_empty() {
        protect_output(&object, inputs)?;
    }
    if !cli.compile_only && !sources.is_empty() && identity(&exe)? == identity(&object)? {
        bail!("Executable and object output must have different paths");
    }
    let mut has_program = false;
    if !sources.is_empty() {
        let (input,origins) = if sources.len() == 1 {
            (sources[0].clone(),None)
        } else {
            let combined = base.with_extension("f90c-sources.f90");
            if identity(&combined)? == identity(&exe)? || identity(&combined)? == identity(&object)?
            {
                bail!(
                    "Output conflicts with combined source: {}",
                    combined.display()
                );
            }
            let origins=combine(&sources, &combined, inputs)?;
            (combined,Some(origins))
        };
        if !cli.quiet {
            eprintln!("Compiling {} -> {}", input.display(), object.display());
        }
        let artifact = compile_to_object(
            &input,
            &object,
            cli.wall,
            cli.werror,
            cli,
            !objects.is_empty(),
            origins.as_deref(),
        )?;
        has_program = artifact.has_program;
        objects.insert(0, artifact.object);
    }
    if cli.compile_only
        || (!has_program && !force_link && objects.len() == 1 && !sources.is_empty())
    {
        if run {
            bail!("No main program to run");
        }
        return Ok(());
    }
    linker::link(&objects, &exe, cli)?;
    if run {
        let status = std::process::Command::new(exe.canonicalize()?)
            .status()
            .context("running compiled program")?;
        if !status.success() {
            std::process::exit(status.code().unwrap_or(1));
        }
    }
    Ok(())
}
