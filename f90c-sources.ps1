# Combine a source group for f90c's whole-program module resolution.
param(
    [Parameter(Mandatory = $true)]
    [string] $Output,
    [Parameter(Mandatory = $true, ValueFromRemainingArguments = $true)]
    [string[]] $Sources
)

$ErrorActionPreference = 'Stop'
try {
    $outputPath = [IO.Path]::GetFullPath($Output)
    $marker = '! Generated by f90c.bat; do not edit.'
    $combined = New-Object Text.StringBuilder
    [void] $combined.AppendLine($marker)
    foreach ($source in $Sources) {
        $sourcePath = [IO.Path]::GetFullPath($source)
        if ([StringComparer]::OrdinalIgnoreCase.Equals($sourcePath, $outputPath)) {
            throw "Combined output would overwrite input: $sourcePath"
        }
        if (-not [IO.File]::Exists($sourcePath)) {
            throw "Source file not found: $sourcePath"
        }
        # ReadAllText removes a UTF BOM; AppendLine separates files even when
        # the preceding source ends with a comment without a final newline.
        $text = [IO.File]::ReadAllText($sourcePath)
        [void] $combined.AppendLine("! Source: $sourcePath")
        [void] $combined.AppendLine($text)
    }
    if ([IO.File]::Exists($outputPath)) {
        $reader = [IO.File]::OpenText($outputPath)
        try { $firstLine = $reader.ReadLine() } finally { $reader.Dispose() }
        if ($firstLine -ne $marker) {
            throw "Refusing to overwrite a file not generated by f90c.bat: $outputPath"
        }
    }
    [IO.File]::WriteAllText($outputPath, $combined.ToString(), (New-Object Text.UTF8Encoding($false)))
    exit 0
} catch {
    [Console]::Error.WriteLine("Error: " + $_.Exception.Message)
    exit 1
}
